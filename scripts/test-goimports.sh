#!/bin/sh
# A gofmt-clean missing import must fail the same non-mutating check used by CI.
set -eu
root=$(pwd)
fixture=$(mktemp -d)
trap 'rm -rf "$fixture"' EXIT HUP INT TERM
cd "$fixture"
git init -q
printf '%s\n' 'module goimports-fixture' 'go 1.27.0' > go.mod
for generated in no yes; do
    if [ "$generated" = yes ]; then
        printf '%s\n' '// Code generated by the goimports smoke fixture. DO NOT EDIT.' > fixture.go
    else
        : > fixture.go
    fi
    printf '%s\n' 'package fixture' '' 'func example() { fmt.Println("not executed") }' >> fixture.go
    cp fixture.go original.go.txt
    if sh "$root/scripts/check-goimports.sh" "$@" > output 2>&1; then
        cat output
        echo "goimports accepted missing import (generated=$generated)" >&2
        exit 1
    fi
    cat output
    grep -F '+import "fmt"' output
    cmp fixture.go original.go.txt
    "$@" -w fixture.go
    sh "$root/scripts/check-goimports.sh" "$@"
done
